"""Rebuild the handheld's antialiased Atkinson Hyperlegible Next glyph subsets."""
from pathlib import Path
from hashlib import sha256
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "game/assets/fonts/AtkinsonHyperlegibleNext.ttf"
TARGET = ROOT / "firmware/WillowCreek/LcdGlyphs.h"
if not SOURCE.is_file():
    release = Path(__file__).resolve().parents[1]
    SOURCE = release / "font-source/AtkinsonHyperlegibleNext.ttf"
    TARGET = release / "WillowCreek/LcdGlyphs.h"
SOURCE_SHA = "5a455d1cfa099b601ab70751bb9673e8fe1854dc4500c80e1a220d0d75e31745"


def generate_face(name, pixels, weight):
    font = ImageFont.truetype(str(SOURCE), pixels)
    font.set_variation_by_axes([weight])
    chars = [chr(code) for code in range(32, 127)]
    baseline = -min(font.getbbox(c, anchor="ls")[1] for c in chars)
    data, glyphs = [], []
    for c in chars:
        image = Image.new("L", (pixels * 3, pixels * 2))
        ImageDraw.Draw(image).text((pixels, baseline), c, font=font, anchor="ls", fill=255)
        image = image.point(lambda value: (value * 3 + 127) // 255)
        box = image.getbbox() or (pixels, baseline, pixels, baseline)
        left, top, right, bottom = box
        glyphs.append((len(data), left-pixels, top, right-left, bottom-top, round(font.getlength(c))))
        values = list(image.crop(box).getdata())
        values += [0] * (-len(values) % 4)
        for i in range(0, len(values), 4):
            data.append((values[i]<<6) | (values[i+1]<<4) | (values[i+2]<<2) | values[i+3])
    output = [f"constexpr Glyph {name}Glyphs[] = {{"]
    output.extend("  {" + ",".join(map(str, g)) + "}," for g in glyphs)
    output.extend(["};", f"constexpr uint8_t {name}Pixels[] = {{"])
    for i in range(0, len(data), 20):
        output.append("  " + ",".join(f"0x{n:02x}" for n in data[i:i+20]) + ",")
    output.extend(["};", f"constexpr Face {name} = {{{name}Glyphs,{name}Pixels}};"])
    return output


if __name__ == "__main__":
    assert sha256(SOURCE.read_bytes()).hexdigest() == SOURCE_SHA, "Review the updated font before rebuilding."
    out = [
        "// Generated by firmware/tools/make_lcd_font.py. Source licensed under SIL OFL 1.1.",
        "#pragma once", "#include <cstdint>", "namespace lcdtype {",
        "struct Glyph { uint16_t offset; int8_t left, top; uint8_t w, h, advance; };",
        "struct Face { const Glyph* glyphs; const uint8_t* pixels; };",
    ]
    for spec in [("caption", 10, 400), ("body", 16, 600), ("title", 24, 600)]:
        out += generate_face(*spec)
    TARGET.write_text("\n".join(out + ["}", ""]), encoding="utf-8")
