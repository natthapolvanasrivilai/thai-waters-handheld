// Bake painted field plates into a shared flash-resident, tightly cropped atlas.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const {PNG}=require(require.resolve('pngjs',{paths:[path.resolve(__dirname,'../lan')]}));
const {extract}=require('./compile.cjs'),dir=path.join(__dirname,'field');
const plates=JSON.parse(fs.readFileSync(path.join(dir,'plates.json'))),fish=JSON.parse(fs.readFileSync(path.join(__dirname,'../content/extended.json')));
const frames=[],packed=[],seen=new Set(),ids=new Map();
// Segment the whole sheet before assigning cells. A long barbel or fin can
// cross a nominal grid boundary while still belonging to the same specimen.
function individuals(p,rows,file){
 const w=p.width,h=p.height,labels=new Int32Array(w*h),queue=new Int32Array(w*h),parts=[];
 const corners=[0,w-1,(h-1)*w,w*h-1].map(i=>p.data[4*i+3]).sort((a,b)=>a-b);
 const cutoff=200;
 if(corners[2]>90){
  // Some transparent originals retain a light paper matte. Remove only paper
  // connected to the outside, preserving enclosed white scales and eyes.
  let written=0;
  function paper(k){
   const i=4*k;if(labels[k]||Math.min(p.data[i],p.data[i+1],p.data[i+2])<228)return;
   labels[k]=-1;queue[written++]=k;
  }
  for(let x=0;x<w;x++){paper(x);paper((h-1)*w+x);}
  for(let y=0;y<h;y++){paper(y*w);paper(y*w+w-1);}
  for(let i=0;i<written;i++){const j=queue[i],x=j%w;if(x)paper(j-1);if(x+1<w)paper(j+1);if(j>=w)paper(j-w);if(j+w<w*h)paper(j+w);}
 }
 let label=0;
 for(let start=0;start<labels.length;start++){
  if(labels[start]||p.data[4*start+3]<cutoff)continue;
  label++;let size=1,left=w,right=0,top=h,bottom=0;labels[start]=label;queue[0]=start;
  for(let i=0;i<size;i++){
   const j=queue[i],x=j%w,y=Math.floor(j/w);
   left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);
   for(const k of [x>0?j-1:-1,x+1<w?j+1:-1,y>0?j-w:-1,y+1<h?j+w:-1]){
    if(k>=0&&!labels[k]&&p.data[4*k+3]>=cutoff){labels[k]=label;queue[size++]=k;}
   }
  }
  if(size>w*h/(rows*4)*.025)parts.push({label,left,right,top,bottom,size});
 }
 const expected=rows*4;parts.sort((a,b)=>b.size-a.size);
 if(parts.length<expected||parts[expected]?.size>parts[expected-1].size*.6)throw Error(file+' needs a cell review: '+parts.length+' components for '+expected+' species');
 const chosen=parts.slice(0,expected).sort((a,b)=>(a.top+a.bottom)-(b.top+b.bottom)),out=[];
 for(let i=0;i<expected;i+=4){
  const row=chosen.slice(i,i+4).sort((a,b)=>(a.left+a.right)-(b.left+b.right));
  for(const part of row){
   const crop=new PNG({width:part.right-part.left+1,height:part.bottom-part.top+1});
   for(let y=0;y<crop.height;y++)for(let x=0;x<crop.width;x++){
    const k=(y+part.top)*w+x+part.left;if(labels[k]!==part.label)continue;
    p.data.copy(crop.data,4*(y*crop.width+x),4*k,4*k+4);
   }
   out.push(crop);
  }
 }
 return out;
}
for(const sheet of plates){
 const bytes=fs.readFileSync(path.join(dir,sheet.file));
 if(crypto.createHash('sha256').update(bytes).digest('hex')!==sheet.sha256)throw Error('Source fingerprint changed '+sheet.file);
 const p=PNG.sync.read(bytes);
 if(sheet.ids.length!==4*sheet.rows)throw Error('Wrong cell count '+sheet.file);
 const cells=individuals(p,sheet.rows,sheet.file);
 for(let n=0;n<sheet.ids.length;n++){
  const id=sheet.ids[n];if(id<60||!fish[id-52]||fish[id-52].name!==sheet.species[n]||ids.has(id))throw Error('Invalid species '+id);
  const {indices,palette}=extract(cells[n],1,0,0,1);
  const hash=crypto.createHash('sha256').update(Buffer.from(indices)).update(JSON.stringify(palette)).digest('hex');
  if(seen.has(hash))throw Error('Repeated portrait '+id);seen.add(hash);
  let left=96,right=0,top=50,bottom=0;indices.forEach((v,i)=>{if(!v)return;const x=i%96,y=Math.floor(i/96);left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);});
  if(right-left<5||bottom-top<4)throw Error('Empty plate '+id);
  const offset=packed.length;for(let y=top;y<=bottom;y++)for(let x=left;x<=right;x+=2)packed.push(indices[y*96+x]*16+(x<right?indices[y*96+x+1]:0));
  ids.set(id,frames.length);frames.push('{'+[offset,left,top,right-left+1,bottom-top+1,'{'+palette.join(',')+'}'].join(',')+'}');
 }
}
const index=Array.from({length:52+fish.length},(_,i)=>ids.get(i)??-1);
const lines=['#pragma once','#include <cstdint>','// Generated by game/art-source/compile-field.cjs','namespace specimen {',
 'struct Frame {uint32_t offset;uint8_t x,y,w,h;uint16_t ink[16];};',
 'constexpr int16_t index[]={'+index.join(',')+'};','constexpr Frame frames[]={'+frames.join(',\n')+'};','constexpr uint8_t packed[]={'];
for(let i=0;i<packed.length;i+=48)lines.push(packed.slice(i,i+48).join(',')+',');
lines.push('};','}');
const output=path.join(__dirname,'../../firmware/WillowCreek/FieldPlates.h'),source=lines.join('\n')+'\n';
if(!fs.existsSync(output)||fs.readFileSync(output,'utf8')!==source)fs.writeFileSync(output,source);
console.log(frames.length+' individual field illustrations, '+packed.length+' packed bytes');