// Bake painted field plates into a shared flash-resident, tightly cropped atlas.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const {PNG}=require(require.resolve('pngjs',{paths:[path.resolve(__dirname,'../lan')]}));
const {extract}=require('./compile.cjs'),dir=path.join(__dirname,'field');
const plates=JSON.parse(fs.readFileSync(path.join(dir,'plates.json'))),fish=JSON.parse(fs.readFileSync(path.join(__dirname,'../content/extended.json')));
const frames=[],packed=[],seen=new Set(),ids=new Map();
const {individuals}=require('./segment-field.cjs');
let embeddedBytes=0,embeddedFrames=0,onCard=false;
const revisedSheets=new Map();
for(const sheet of plates){
 const bytes=fs.readFileSync(path.join(dir,sheet.file));
 if(crypto.createHash('sha256').update(bytes).digest('hex')!==sheet.sha256)throw Error('Source fingerprint changed '+sheet.file);
 const p=PNG.sync.read(bytes);
 if(sheet.ids.length!==(sheet.columns??4)*sheet.rows)throw Error('Wrong cell count '+sheet.file);
 const cells=individuals(p,sheet.rows,sheet.file,sheet.columns??4);
 for(let n=0;n<sheet.ids.length;n++){
  const id=sheet.ids[n];if(id<60||!fish[id-52]||fish[id-52].name!==sheet.species[n]||ids.has(id))throw Error('Invalid species '+id);
  let cell=cells[n];
  const revision=sheet.replacements?.[id];
  if(revision){
   if(revision.reference){
    const ref=fs.readFileSync(path.join(dir,revision.reference));
    if(crypto.createHash('sha256').update(ref).digest('hex')!==revision.reference_sha256)throw Error('Anatomy reference changed '+revision.reference);
   }
   const bytes=fs.readFileSync(path.join(dir,revision.file));
   if(crypto.createHash('sha256').update(bytes).digest('hex')!==revision.sha256)throw Error('Source fingerprint changed '+revision.file);
   if(!revisedSheets.has(revision.file))revisedSheets.set(revision.file,
    individuals(PNG.sync.read(bytes),revision.rows??1,revision.file,revision.columns??1));
   cell=revisedSheets.get(revision.file)[(revision.cell??1)-1];
   if(!cell)throw Error('Replacement cell outside plate '+revision.file);
  }
  const {indices,palette}=extract(cell,1,0,0,1);
  const hash=crypto.createHash('sha256').update(Buffer.from(indices)).update(JSON.stringify(palette)).digest('hex');
  if(seen.has(hash))throw Error('Repeated portrait '+id);seen.add(hash);
  let left=96,right=0,top=50,bottom=0;indices.forEach((v,i)=>{if(!v)return;const x=i%96,y=Math.floor(i/96);left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);});
  if(right-left<5||bottom-top<4)throw Error('Empty plate '+id);
  const offset=packed.length;for(let y=top;y<=bottom;y++)for(let x=left;x<=right;x+=2)packed.push(indices[y*96+x]*16+(x<right?indices[y*96+x+1]:0));
  ids.set(id,frames.length);frames.push('{'+[offset,left,top,right-left+1,bottom-top+1,'{'+palette.join(',')+'}'].join(',')+'}');
 }
 if(sheet.storage==='card')onCard=true;
 else{
  if(sheet.storage||onCard)throw Error('Keep resident plates before card plates');
  embeddedBytes=packed.length;embeddedFrames=frames.length;
 }
}
const index=Array.from({length:52+fish.length},(_,i)=>ids.get(i)??-1);
const fw=path.join(__dirname,'../../firmware/WillowCreek');
function write(file,data){
 const value=Buffer.from(data);
 if(!fs.existsSync(file)||!fs.readFileSync(file).equals(value))fs.writeFileSync(file,value);
}
const bank=Buffer.from(packed.slice(embeddedBytes));
const digest=crypto.createHash('sha256').update(bank).digest();
write(path.join(__dirname,'../assets/TW-FISH.BIN'),bank);
const manifest=['#pragma once','#include <cstdint>','// Generated by game/art-source/compile-field.cjs','namespace specimen {',
 'inline constexpr int16_t index[]={'+index.join(',')+'};',
 'inline constexpr int residentFrames='+embeddedFrames+';',
 'inline constexpr uint32_t residentBytes='+embeddedBytes+', cardBytes='+bank.length+';',
 'inline constexpr uint8_t cardDigest[]={'+[...digest].join(',')+'};','}'];
write(path.join(fw,'SpecimenIndex.h'),manifest.join('\n')+'\n');
const lines=['#pragma once','#include "SpecimenIndex.h"','namespace specimen {',
 'struct Frame {uint32_t offset;uint8_t x,y,w,h;uint16_t ink[16];};',
 'inline constexpr Frame frames[]={'+frames.join(',\n')+'};','inline constexpr uint8_t packed[]={'];
for(let i=0;i<embeddedBytes;i+=48)lines.push(packed.slice(i,Math.min(embeddedBytes,i+48)).join(',')+',');
lines.push('};','}');
write(path.join(fw,'FieldPlates.h'),lines.join('\n')+'\n');
console.log(frames.length+' illustrations, '+embeddedBytes+' resident pixel bytes, '+bank.length+' card pixel bytes');
