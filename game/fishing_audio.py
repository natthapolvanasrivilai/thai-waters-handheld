"""Bake the original 16 kHz fishing foley into signed 8-bit mono clips for both game mixers."""
from pathlib import Path
import math
import random

RATE = 16000
TAU = 2 * math.pi

def bake(kind, seconds, seed):
    rng = random.Random(seed)
    low = prev = phase = 0.0
    samples = []
    teeth = []
    t = 0
    while t < seconds:
        teeth.append(t)
        t += (0.018 + 0.018 * t / seconds) * rng.uniform(.93, 1.07)
    for i in range(round(RATE * seconds)):
        t = i / RATE
        u = t / seconds
        noise = rng.uniform(-1, 1)
        low += (.13 + .12 * (1-u)) * (noise-low)
        bright = noise - prev
        prev = noise
        if kind == 'Air':
            sweep = math.exp(-((t-.185)/.083)**2)
            phase += TAU*(410+1300*sweep)/RATE
            v = sweep*(.65*low+.14*bright+.09*math.sin(phase))
        elif kind == 'Spool':
            age = t-max(a for a in teeth if a <= t)
            hz = 3150-680*u
            v = (.55*math.sin(TAU*hz*age)+.25*bright)*math.exp(-age*1200)*(1-.65*u)
        elif kind in ('Splash','Pull'):
            v = ((.76*low+.19*bright)*math.exp(-t*(13 if kind=='Splash' else 25)) +
                 .22*math.sin(TAU*(220*t+460*t*t))*math.exp(-t*24))
            for delay,pitch in ((.047,950),(.098,1200),(.16,730)):
                if t >= delay:
                    d = t-delay
                    v += .14*math.sin(TAU*(pitch*d+4100*d*d))*math.exp(-d*68)
        else:
            # Brittle break, then the pitched recoil of the suddenly unloaded line.
            v = .74*bright*math.exp(-t*380)+.44*math.sin(TAU*(2500*t-4200*t*t))*math.exp(-t*34)
            if t>.029:
                d=t-.029
                v+=.29*math.sin(TAU*(740*d-900*d*d))*math.exp(-d*28)
        v *= min(1.,i/8,(seconds-t)*150)
        samples.append(max(-127,min(127,round(v*124))))
    return samples

def main():
    out=['#pragma once','#include <cstdint>','// Generated by game/fishing_audio.py. Signed mono PCM at 16 kHz.','namespace fishingpcm {']
    for i,(name,duration) in enumerate([('Air',.42),('Spool',.64),('Splash',.37),('Pull',.24),('Snap',.26)]):
        samples=bake(name,duration,3701+i)
        out.append('static constexpr int8_t '+name+'[]={')
        out.extend(','.join(map(str,samples[j:j+40]))+',' for j in range(0,len(samples),40))
        out.append('};')
    out.append('}')
    (Path(__file__).resolve().parents[1]/'firmware/WillowCreek/FishingPcm.h').write_text('\n'.join(out)+'\n',encoding='ascii')

if __name__=='__main__':
    main()
