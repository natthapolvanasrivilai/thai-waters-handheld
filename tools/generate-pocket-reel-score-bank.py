"""Generate original note samples at 12 kHz. No input samples or dependencies."""
from pathlib import Path
from math import sin, exp, pi, tanh
from random import Random

RATE=12000
SIZE=6600
ROOTS=(196,196,98,196)

def note(kind, hz):
    rng=Random(0x22765+kind)
    period=round(RATE/hz)
    x=[rng.uniform(-1,1) for _ in range(period*2)]
    line=[(x[i]+x[i+1]+x[i+2])/3 for i in range(period)]
    p=random_body=previous=0
    out=[]
    for i in range(SIZE):
        t=i/RATE
        a=2*pi*hz*t
        r=rng.uniform(-1,1)
        random_body=.84*random_body+.16*r
        if kind==0 or kind==2:
            delayed=line[p]
            nxt=(p+1)%period
            line[p]=(.52*delayed+.48*line[nxt])*(.996 if kind==0 else .998)
            p=nxt
            sympathetic=sin(a*.9994+.15*sin(2*pi*1.12*t))
            if kind==0:
                v=delayed*.82+ .43*exp(-4.8*t)*sympathetic + .12*exp(-38*t)*sin(a*2.04)
                v+=.11*exp(-74*t)*(r-random_body)
            else:
                v=.38*delayed+.68*exp(-4.5*t)*sympathetic+.19*exp(-9*t)*sin(2*a+.54)
                v+=.08*exp(-40*t)*(r-random_body)
            previous=.63*previous+.37*v
            v=previous if kind==2 else .66*v+.34*previous
            v*=min(1,t/(.004 if kind==0 else .009))
        elif kind==1:
            # Unequal tine and pickup decay + mechanical hammer/keybed transient.
            v=.59*sin(a)*exp(-4.2*t)+.23*sin(a*2.003+.22)*exp(-7.1*t)
            v+=.17*sin(a*2.756+.4)*exp(-18*t)+.045*sin(a*5.29)*exp(-31*t)
            v=tanh(1.18*v)+.08*exp(-56*t)*(r-random_body)
            v*=min(1,t/.009)
        else:
            # Quiet tape-string character: staggered fingerings, bounded vibrato, bow texture.
            a+=.075*sin(2*pi*4.65*t)+.035*sin(2*pi*1.23*t)
            v=.47*sin(a)+.21*sin(a*2.006+.23)+.13*sin(3*a)+.055*sin(4*a-.18)
            v+=.10*sin(a*.996-.41)+ .12*random_body
            v*=min(1,t/.035)*(1-.18*t)
        out.append(round(v*min(1,(SIZE-1-i)/300)*100))
    peak=max(abs(x) for x in out)
    return [round(v*115/peak) for v in out]

def render():
    lines=['// Generated by tools/generate-pocket-reel-score-bank.py (original samples; no external material).',
           '#pragma once','#include <stdint.h>','namespace locationaudio { namespace instruments {',
           f'constexpr unsigned rate={RATE}, frames={SIZE};',
           'constexpr unsigned rootsCentiHz[]={19600,19600,9800,19600};',
           'constexpr int8_t pcm[4][frames]={']
    for kind,root in enumerate(ROOTS):
        data=note(kind,root)
        lines.append(' {')
        for i in range(0,SIZE,24): lines.append('  '+','.join(map(str,data[i:i+24]))+',')
        lines.append(' },')
    lines.extend(['};','}}',''])
    return '\n'.join(lines)

if __name__=='__main__':
    target=Path(__file__).resolve().parents[1]/'firmware/WillowCreek/ScoreInstruments.h'
    target.write_text(render(),encoding='ascii')
