'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'../..');
const source=fs.readFileSync(path.join(root,'game/src/location-map-model.js'),'utf8');
const {create,createTouchActivation}=vm.runInNewContext(source+'\nwaterbodyMapModel');
const geo=JSON.parse(fs.readFileSync(path.join(root,'game/content/map-pilot.geojson'),'utf8'));
const rows=geo.features.map(r=>[r.id,...r.geometry.coordinates]), map=create(rows,230,186);
const mae=map.position(0),phayao=map.position(16);
const local=(a,x=a[0],y=a[1])=>({x:a[0],y:a[1],clientX:x,clientY:y});
assert.equal(rows.length,9);
assert.ok(phayao[0]>mae[0]&&Math.abs(phayao[1]-mae[1])<1);
assert.equal(map.selected(),null);
assert.equal(map.pick(...mae),0);
assert.equal(map.pick(...phayao),16);
assert.equal(map.pick(9,9),null);
assert.equal(map.choose(117),false);
assert.equal(map.start(8,local(phayao)),true);
assert.equal(map.start(9,local(mae)),false);
assert.equal(map.move(9,local([15,15])),false);
assert.equal(map.end(8,local(phayao)),true);
assert.equal(map.selected(),16);
assert.equal(map.start(1,local(mae)),true);
assert.equal(map.move(1,local([250,240])),true);
assert.equal(map.end(1,local([250,240])),false);
assert.equal(map.selected(),16,'drag from a marker never changes selection');
assert.equal(JSON.stringify(map.pan()),'[44,26]');
map.resetPan();
assert.equal(JSON.stringify(map.pan()),'[0,0]');
assert.equal(map.selected(),16,'reset moves viewport only');
map.panBy(-800,-800);
assert.equal(JSON.stringify(map.pan()),'[-44,-26]');
map.resetPan();
assert.equal(map.start(1,local(mae)),true);
assert.equal(map.cancel(1),true);
assert.equal(map.end(1,local(mae)),false);
assert.equal(map.selected(),16);
assert.equal(map.start(1,local(mae)),true);
assert.equal(map.end(1,local(mae)),true);
assert.equal(map.selected(),0,'zero is a real existing destination');
assert.equal(map.start(1,local(mae,0,0)),true);
assert.equal(map.move(1,local(mae,1,1)),false);
assert.equal(map.end(1,local(mae,8,0)),false);
let calls=[];
assert.equal(map.confirm(false,id=>calls.push(id)),false);
assert.equal(map.confirm(true,id=>{calls.push(id);return true}),true);
assert.deepEqual(calls,[0]);
map.choose(null);
assert.equal(map.confirm(true,()=>{throw Error('disabled')}),false);
console.log('PASS 9 sourced IDs; pan, reset and cancel preserve selection; explicit guarded travel; zero is valid');

const touch=createTouchActivation(), fires=[];
const at=(more={})=>({pointerId:7,pointerType:'touch',isPrimary:true,isTrusted:true,button:0,
 clientX:100,clientY:100,timeStamp:200,detail:1,...more});
const accept=id=>{fires.push(id);return true;};
const click=more=>touch.consume(at(more));
assert.equal(touch.down(at(),16),true);
assert.equal(touch.up(at({timeStamp:265}),16,accept),true);
assert.deepEqual(fires,[16],'one actual touch pair suffices without compatibility click');
assert.equal(click({detail:0}),false,'keyboard and assistive activation stay independent');
assert.equal(click({isTrusted:false}),false,'untrusted click does not swallow a pending genuine contact');
assert.equal(click({pointerId:8}),false,'different native pointer not consumed');
assert.equal(click({pointerType:'mouse'}),false,'ordinary independent mouse click stays available');
assert.equal(click({clientX:140}),false,'unrelated click location unaffected');
assert.equal(click({timeStamp:280}),true,'dedupe exact trusted compatibility click');
assert.equal(click({timeStamp:281}),false,'dedupe token is one-use');
assert.equal(touch.down(at(),16),true);
touch.move(at({clientX:113}));
assert.equal(touch.up(at(),16,accept),false,'drag out and back cannot activate');
assert.equal(touch.down(at(),16),true);
touch.cancel(at());
assert.equal(touch.up(at(),16,accept),false,'capture loss or cancel cannot activate');
assert.equal(touch.down(at(),16),true);
assert.equal(touch.down(at({pointerId:8,isPrimary:false}),16),false);
assert.equal(touch.up(at(),16,accept),false,'multitouch invalidates the initial contact');
assert.equal(touch.down(at(),16),true);
assert.equal(touch.up(at({pointerId:8}),16,accept),false,'mismatched release never activates');
assert.equal(touch.up(at(),2,accept),false,'changed selection cancels pending contact');
assert.equal(touch.down(at(),16),true);
assert.equal(touch.up(at(),null,accept),false,'disabled or uncovered control cannot activate');
assert.equal(touch.down(at({isTrusted:false}),16),false);
assert.equal(touch.down(at({pointerType:'mouse'}),16),false);
assert.deepEqual(fires,[16]);
assert.equal(touch.down(at(),0),true);
assert.equal(touch.up(at(),0,accept),true,'destination ID zero is a valid touch scope');
assert.equal(click({pointerType:undefined,pointerId:undefined,timeStamp:240}),true,'legacy synthesized click fallback');
assert.equal(touch.down(at(),0),true);
assert.equal(touch.up(at(),0,accept),true);
assert.equal(click({timeStamp:710}),false,'stale tokens do not consume clicks');
assert.equal(touch.down(at(),0),true);
assert.equal(touch.up(at(),0,accept),true);
touch.down(at({pointerId:9,pointerType:'mouse'}),null);
assert.equal(click({timeStamp:250}),false,'subsequent genuine pointerdown resets old dedupe');
console.log('PASS native touch qualification, refusal paths, exact compatibility-click dedupe and keyboard independence');
