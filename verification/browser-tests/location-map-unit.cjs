'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'../..');
const source=fs.readFileSync(path.join(root,'game/src/location-map-model.js'),'utf8');
const {create}=vm.runInNewContext(source+'\nwaterbodyMapModel');
const geo=JSON.parse(fs.readFileSync(path.join(root,'game/content/map-pilot.geojson'),'utf8'));
const rows=geo.features.map(r=>[r.id,...r.geometry.coordinates]), map=create(rows,230,186);
const mae=map.position(0),phayao=map.position(16);
const local=(a,x=a[0],y=a[1])=>({x:a[0],y:a[1],clientX:x,clientY:y});
assert.equal(rows.length,9);
assert.ok(phayao[0]>mae[0]&&Math.abs(phayao[1]-mae[1])<1);
assert.equal(map.selected(),null);
assert.equal(map.pick(...mae),0);
assert.equal(map.pick(...phayao),16);
assert.equal(map.pick(9,9),null);
assert.equal(map.choose(117),false);
assert.equal(map.start(8,local(phayao)),true);
assert.equal(map.start(9,local(mae)),false);
assert.equal(map.move(9,local([15,15])),false);
assert.equal(map.end(8,local(phayao)),true);
assert.equal(map.selected(),16);
assert.equal(map.start(1,local(mae)),true);
assert.equal(map.move(1,local([250,240])),true);
assert.equal(map.end(1,local([250,240])),false);
assert.equal(map.selected(),16,'drag from a marker never changes selection');
assert.equal(JSON.stringify(map.pan()),'[44,26]');
map.resetPan();
assert.equal(JSON.stringify(map.pan()),'[0,0]');
assert.equal(map.selected(),16,'reset moves viewport only');
map.panBy(-800,-800);
assert.equal(JSON.stringify(map.pan()),'[-44,-26]');
map.resetPan();
assert.equal(map.start(1,local(mae)),true);
assert.equal(map.cancel(1),true);
assert.equal(map.end(1,local(mae)),false);
assert.equal(map.selected(),16);
assert.equal(map.start(1,local(mae)),true);
assert.equal(map.end(1,local(mae)),true);
assert.equal(map.selected(),0,'zero is a real existing destination');
assert.equal(map.start(1,local(mae,0,0)),true);
assert.equal(map.move(1,local(mae,1,1)),false);
assert.equal(map.end(1,local(mae,8,0)),false);
let calls=[];
assert.equal(map.confirm(false,id=>calls.push(id)),false);
assert.equal(map.confirm(true,id=>{calls.push(id);return true}),true);
assert.deepEqual(calls,[0]);
map.choose(null);
assert.equal(map.confirm(true,()=>{throw Error('disabled')}),false);
console.log('PASS 9 sourced IDs; pan, reset and cancel preserve selection; explicit guarded travel; zero is valid');
